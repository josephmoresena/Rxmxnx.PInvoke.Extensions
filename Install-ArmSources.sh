#!/usr/bin/env bash
set -euo pipefail

# Configure Ubuntu multiarch repositories for GitHub Actions.
# Noble (24.04): arm64 and armhf from Ubuntu Ports.
# Resolute (26.04): arm64 from the main archive; armhf from Ubuntu Ports.
# The runner's native amd64 sources are preserved.

if [[ ! -r /etc/os-release ]]; then
    echo "Missing /etc/os-release." >&2
    exit 1
fi

# shellcheck disable=SC1091
. /etc/os-release

suite="${UBUNTU_CODENAME:-${VERSION_CODENAME:-}}"
ubuntu_major="${VERSION_ID%%.*}"

if [[ -z "$suite" || ! "$ubuntu_major" =~ ^[0-9]+$ ]]; then
    echo "Unable to determine Ubuntu release." >&2
    exit 1
fi

if [[ "$ID" != "ubuntu" ]]; then
    echo "Expected Ubuntu; detected ID=${ID:-unknown}." >&2
    exit 1
fi

if [[ "$(dpkg --print-architecture)" != "amd64" ]]; then
    echo "This script expects an amd64 GitHub Actions runner." >&2
    exit 1
fi

# Determine which architectures the primary Ubuntu archive serves.
host_archs="amd64"
port_archs="arm64,armhf"

if (( ubuntu_major >= 26 )); then
    host_archs="amd64,arm64"
    port_archs="armhf"
fi

echo "Ubuntu release: ${suite}"
echo "Main archive architectures: ${host_archs}"
echo "Ubuntu Ports architectures: ${port_archs}"

# Enable the foreign architectures.
sudo dpkg --add-architecture arm64
sudo dpkg --add-architecture armhf

# Remove files generated by earlier versions of this script.
sudo rm -f \
    /etc/apt/sources.list.d/arm64.list \
    /etc/apt/sources.list.d/armhf.list \
    /etc/apt/sources.list.d/arm-ports.list

# Rewrite Ubuntu source architecture restrictions in both .list and
# DEB822 .sources files. Third-party repositories are left untouched.
sudo HOST_ARCHS="$host_archs" python3 - <<'PY'
import os
import re
from pathlib import Path

host_archs = os.environ["HOST_ARCHS"].split(",")

ubuntu_hosts = (
    "archive.ubuntu.com",
    "security.ubuntu.com",
    "azure.archive.ubuntu.com",
    "ubuntu.com",
)

def is_ubuntu_uri(uri):
    # GitHub Actions uses a local mirror list to resolve Ubuntu mirrors.
    if uri.startswith("mirror+file:/etc/apt/apt-mirrors.txt"):
        return True

    return any(
        uri == host or uri.endswith("." + host)
        for host in ubuntu_hosts
    )

def restrict_deb822(path):
    content = path.read_text()
    blocks = re.split(r"\n\s*\n", content)
    result = []
    changed = False

    for block in blocks:
        lines = block.splitlines()

        if not lines:
            result.append(block)
            continue

        uris_index = next(
            (
                i for i, line in enumerate(lines)
                if re.match(r"^\s*URIs\s*:", line, re.I)
            ),
            None,
        )

        if uris_index is None:
            result.append(block)
            continue

        uris = lines[uris_index].split(":", 1)[1].split()

        # Only change Ubuntu archive sources.
        if not uris or not all(is_ubuntu_uri(uri) for uri in uris):
            result.append(block)
            continue

        # Replace existing architecture restrictions or add one.
        arch_indices = [
            i for i, line in enumerate(lines)
            if re.match(r"^\s*Architectures\s*:", line, re.I)
        ]

        if arch_indices:
            lines[arch_indices[0]] = (
                "Architectures: " + " ".join(host_archs)
            )

            # Remove duplicate architecture fields if present.
            for index in reversed(arch_indices[1:]):
                del lines[index]
        else:
            lines.append("Architectures: " + " ".join(host_archs))

        result.append("\n".join(lines))
        changed = True

    if changed:
        path.write_text("\n\n".join(result).rstrip() + "\n")

def restrict_legacy_list(path):
    content = path.read_text()
    output = []
    changed = False

    for line in content.splitlines():
        match = re.match(
            r"^(\s*deb(?:-src)?\s+)(?:\[([^\]]*)\]\s*)?(\S+)(.*)$",
            line,
        )

        if not match:
            output.append(line)
            continue

        prefix, options, uri, remainder = match.groups()

        if not is_ubuntu_uri(uri):
            output.append(line)
            continue

        # Preserve other options, but replace any existing arch= option.
        option_list = (options or "").split()
        option_list = [
            option for option in option_list
            if not option.startswith("arch=")
        ]

        option_list.append("arch=" + ",".join(host_archs))

        output.append(
            prefix + "[" + " ".join(option_list) + "] "
            + uri + remainder
        )
        changed = True

    if changed:
        path.write_text("\n".join(output) + "\n")

# Process the conventional source list.
legacy = Path("/etc/apt/sources.list")

if legacy.is_file():
    restrict_legacy_list(legacy)

# Process source files without following symlinks.
source_dir = Path("/etc/apt/sources.list.d")

if source_dir.is_dir():
    for path in source_dir.iterdir():
        if path.is_symlink() or not path.is_file():
            continue

        if path.suffix == ".sources":
            restrict_deb822(path)
        elif path.suffix == ".list":
            restrict_legacy_list(path)

PY

# Install a dedicated Ubuntu Ports source for foreign ARM architectures.
# Include security updates as well as release, updates and backports.
sudo tee /etc/apt/sources.list.d/arm-ports.list >/dev/null <<EOF
deb [arch=${port_archs}] https://ports.ubuntu.com/ubuntu-ports/ ${suite} main restricted universe multiverse
deb [arch=${port_archs}] https://ports.ubuntu.com/ubuntu-ports/ ${suite}-updates main restricted universe multiverse
deb [arch=${port_archs}] https://ports.ubuntu.com/ubuntu-ports/ ${suite}-backports main restricted universe multiverse
deb [arch=${port_archs}] https://ports.ubuntu.com/ubuntu-ports/ ${suite}-security main restricted universe multiverse
EOF

# Restrict the Microsoft repository to architectures supported by the
# runner configuration, avoiding unnecessary armhf index requests.
sudo sed -i \
    's/arch=amd64,arm64,armhf/arch=amd64,arm64/g' \
    /etc/apt/sources.list.d/microsoft-prod.list 2>/dev/null || true

echo "=== Configured Ubuntu source architectures ==="

grep -R -n -E \
    '^(Architectures:|URIs:|deb \[arch=)' \
    /etc/apt/sources.list \
    /etc/apt/sources.list.d \
    2>/dev/null || true

echo "=== Ubuntu DEB822 configuration ==="
cat /etc/apt/sources.list.d/ubuntu.sources 2>/dev/null || true

# Fail the workflow if the package indexes cannot be refreshed.
sudo apt-get update
